import { COLOR_ROLES, SECTORS, sectorColors, themes, type ThemeName } from './colors';
import {
  componentContainer,
  componentRadius,
  componentSpacing,
  componentTypography,
} from './components';
import {
  cubicBezier,
  fontFamily,
  motion,
  radius,
  shadows,
  spacing,
  typography,
  type TypeToken,
} from './scale';

export const CSS_VAR_PREFIX = '--sarwa-';

export function cssVarName(token: string): string {
  return `${CSS_VAR_PREFIX}${token}`;
}

export function themeVariables(theme: ThemeName): Record<string, string> {
  const vars: Record<string, string> = {};
  for (const role of COLOR_ROLES) vars[cssVarName(role)] = themes[theme][role];
  for (const sector of SECTORS) {
    vars[cssVarName(`sector-${sector}`)] = sectorColors[theme][sector].fg;
    vars[cssVarName(`sector-${sector}-subtle`)] = sectorColors[theme][sector].bg;
  }
  for (const [level, value] of Object.entries(shadows[theme])) {
    vars[cssVarName(`shadow-${level}`)] = value;
  }
  return vars;
}

function block(vars: Record<string, string>, indent: string): string {
  return Object.entries(vars)
    .map(([name, value]) => `${indent}${name}: ${value};`)
    .join('\n');
}

function familyList(families: readonly string[]): string {
  return families.map((f) => (f.includes(' ') ? `"${f}"` : f)).join(', ');
}

const px = (n: number): string => (n === 0 ? '0' : `${n / 16}rem`);

const HEADER =
  '/* Generated by @sarwa/tokens from the Mini Trading design system — do not edit by hand. */';

export function colorNames(): string[] {
  return [...COLOR_ROLES, ...SECTORS.flatMap((s) => [`sector-${s}`, `sector-${s}-subtle`])];
}

function typographyUtilities(): string {
  return Object.entries({ ...typography, ...componentTypography } as Record<string, TypeToken>)
    .map(([name, t]) => {
      const rules = [
        `font-family: var(--font-${t.family});`,
        `font-size: ${px(t.size)};`,
        `line-height: ${px(t.lineHeight)};`,
        `font-weight: ${t.weight};`,
        t.tracking === undefined ? '' : `letter-spacing: ${t.tracking}em;`,
        t.uppercase ? 'text-transform: uppercase;' : '',
        t.tabular ? 'font-variant-numeric: tabular-nums;' : '',
      ].filter(Boolean);
      return `@utility type-${name} {\n  ${rules.join('\n  ')}\n}`;
    })
    .join('\n\n');
}

export function buildWebThemeCss(): string {
  const colors = colorNames()
    .map((name) => `  --color-${name}: var(${cssVarName(name)});`)
    .join('\n');
  const radii = Object.entries(radius)
    .map(([k, v]) => `  --radius-${k}: ${k === 'full' ? '9999px' : px(v)};`)
    .join('\n');
  const componentSizes = [
    ...Object.entries(componentSpacing).map(([k, v]) => `  --spacing-${k}: ${px(v)};`),
    ...Object.entries(componentRadius).map(([k, v]) => `  --radius-${k}: ${px(v)};`),
    ...Object.entries(componentContainer).map(([k, v]) => `  --container-${k}: ${px(v)};`),
  ].join('\n');
  const shadowsCss = Object.keys(shadows.dark)
    .map((level) => `  --shadow-${level}: var(${cssVarName(`shadow-${level}`)});`)
    .join('\n');

  return `${HEADER}

@custom-variant dark (&:where(.dark, .dark *));

@theme inline {
${colors}
${radii}
${componentSizes}
${shadowsCss}
  --font-sans: ${familyList(fontFamily.sans)};
  --font-display: ${familyList(fontFamily.display)};
  --font-mono: ${familyList(fontFamily.mono)};
  --ease-standard: ${cubicBezier(motion.easing.standard)};
  --ease-exit: ${cubicBezier(motion.easing.exit)};
  --ease-spring: ${cubicBezier(motion.easing.spring)};
  --animate-flash-up: sarwa-flash-up ${motion.duration.flash}ms ${cubicBezier(motion.easing.standard)};
  --animate-flash-down: sarwa-flash-down ${motion.duration.flash}ms ${cubicBezier(motion.easing.standard)};
  --animate-star-pop: sarwa-star-pop ${motion.duration.slow}ms ${cubicBezier(motion.easing.spring)};
  --animate-live-pulse: sarwa-live-pulse 2s ${cubicBezier(motion.easing.standard)} infinite;
  --animate-blink: sarwa-blink 1s ease-in-out infinite;
  --animate-shimmer: sarwa-shimmer 1.4s ease infinite;
}

/* Light by default; dark follows the OS unless the user picked a theme (.light / .dark on <html>). */
:root {
  color-scheme: light;
${block(themeVariables('light'), '  ')}
}

@media (prefers-color-scheme: dark) {
  :root:not(.light) {
    color-scheme: dark;
${block(themeVariables('dark'), '    ')}
  }
}

:root.dark {
  color-scheme: dark;
${block(themeVariables('dark'), '  ')}
}

@keyframes sarwa-flash-up {
  0% { background-color: var(${cssVarName('flash-up')}); }
  100% { background-color: transparent; }
}
@keyframes sarwa-flash-down {
  0% { background-color: var(${cssVarName('flash-down')}); }
  100% { background-color: transparent; }
}
@keyframes sarwa-star-pop {
  0% { transform: scale(0.6); }
  60% { transform: scale(1.22); }
  100% { transform: scale(1); }
}
@keyframes sarwa-live-pulse {
  0% { box-shadow: 0 0 0 0 color-mix(in srgb, currentColor 55%, transparent); }
  70% { box-shadow: 0 0 0 6px transparent; }
  100% { box-shadow: 0 0 0 0 transparent; }
}
@keyframes sarwa-blink {
  50% { opacity: 0.3; }
}
@keyframes sarwa-shimmer {
  0% { background-position: 100% 0; }
  100% { background-position: 0 0; }
}

${typographyUtilities()}

@utility skeleton-shimmer {
  background: linear-gradient(90deg, var(${cssVarName('skel-a')}) 25%, var(${cssVarName('skel-b')}) 40%, var(${cssVarName('skel-a')}) 60%);
  background-size: 400% 100%;
}

/* Reduced motion: no background fade — a 2 px underline in pos/neg instead (design system rule). */
@media (prefers-reduced-motion: reduce) {
  .animate-flash-up { animation: none; box-shadow: inset 0 -${motion.reduced.flashUnderlinePx}px 0 var(${cssVarName('pos')}); }
  .animate-flash-down { animation: none; box-shadow: inset 0 -${motion.reduced.flashUnderlinePx}px 0 var(${cssVarName('neg')}); }
  .animate-star-pop, .animate-live-pulse, .animate-blink, .animate-shimmer { animation: none; }
}
`;
}

export function buildNativeThemeCss(): string {
  return `${HEADER}
:root {
${block(themeVariables('light'), '  ')}
}

@media (prefers-color-scheme: dark) {
  :root {
${block(themeVariables('dark'), '    ')}
  }
}
`;
}

export function spacingPx(): Record<string, string> {
  return Object.fromEntries(
    Object.entries({ ...spacing, ...componentSpacing }).map(([k, v]) => [k, `${v}px`]),
  );
}

export function radiusPx(): Record<string, string> {
  return Object.fromEntries(
    Object.entries({ ...radius, ...componentRadius }).map(([k, v]) => [k, `${v}px`]),
  );
}
