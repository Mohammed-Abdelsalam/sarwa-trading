export function checkPassword(password: string): PasswordIssue[] {
  const issues: PasswordIssue[] = [];
  if (password.length < PASSWORD_POLICY.minLength) issues.push('TOO_SHORT');
  if (password.length > PASSWORD_POLICY.maxLength) issues.push('TOO_LONG');
  if (COMMON_PASSWORDS.has(password.trim().toLowerCase())) issues.push('COMMON');
  return issues;
}

// Character kinds used: lower, upper, digit, anything else.
function variety(password: string): number {
  return [/[a-z]/, /[A-Z]/, /\d/, /[^a-zA-Z\d]/].filter((kind) => kind.test(password)).length;
}

export function passwordStrength(password: string): PasswordStrength {
  if (password.length === 0) return 0;
  if (checkPassword(password).length > 0) return 1;
  const kinds = variety(password);
  if (password.length >= 16 || (password.length >= 12 && kinds >= 3)) return 4;
  if (password.length >= 12 || kinds >= 3) return 3;
  return 2;
}

// The meter's "add a number or symbol" tip.
export function needsNumberOrSymbol(password: string): boolean {
  return !/[^a-zA-Z]/.test(password);
}
